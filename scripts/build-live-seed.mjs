// Writes supabase/seed-live.sql: the start of the real (non-demo) site on a project that already ran
// the migrations. It keeps only the medicine catalog and the default settings, removes the demo
// accounts (@madad.test) and all demo data, and turns demo mode off. Real accounts are kept.
// DESTRUCTIVE: back the data up first (docs/GO_LIVE.md). To bring the demo back, run supabase/seed.sql.
import { readFileSync, writeFileSync } from 'node:fs';

const seed = (name) => JSON.parse(readFileSync(new URL(`../src/data/mock/seed/${name}.json`, import.meta.url), 'utf8'));
const categories = seed('categories');
const medicines = seed('medicines').filter((m) => (m.status ?? 'approved') === 'approved');

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => (xs?.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const values = (rows) => rows.map((r) => `  (${r.join(', ')})`).join(',\n');

const sql = `-- GENERATED by scripts/build-live-seed.mjs from src/data/mock/seed/{categories,medicines}.json.
-- The real site's starting point: medicine catalog + default settings. No organizations, stock,
-- search logs or demo accounts. Barcodes are left empty: the demo ones are invented.
-- DESTRUCTIVE. Back up first; supabase/seed.sql brings the demo back.
begin;

select set_config('madad.audit', 'off', true);

truncate public.organizations, public.medicines, public.categories, public.search_logs, public.page_views,
  public.reports, public.audit_log, public.notifications, public.favorites, public.availability_alerts,
  public.inquiries, public.announcements cascade;

-- Same defaults as the demo seed (scripts/build-seed.mjs).
update public.settings set value = case key
  when 'fresh_hours' then '24'::jsonb
  when 'expire_hours' then '72'::jsonb
  when 'price_max_days' then '14'::jsonb
  when 'program_confirm_days' then '7'::jsonb
  when 'disclaimer_ar' then 'null'::jsonb
  when 'disclaimer_en' then 'null'::jsonb
  when 'required_docs' then '{"pharmacy":["practice_license","pharmacy_license","contact_id"],"hospital":["facility_license","contact_id"],"medical_point":["authorization_letter","contact_id"],"humanitarian":["registration_certificate","contact_id"]}'::jsonb
  when 'rejection_reasons' then '["وثائق غير واضحة أو ناقصة","الرخصة غير سارية","البيانات لا تطابق الوثائق","مؤسسة مكررة"]'::jsonb
  when 'demo_mode' then 'false'::jsonb
  else value end;

-- The demo accounts and the demo seed function go; real accounts stay, without any demo flag.
delete from auth.users where email like '%@madad.test';
update public.profiles set is_demo = false where is_demo;
drop function if exists public.demo_seed();

insert into public.categories (id, name_ar, name_en, sort_order) values
${values(categories.map((c, i) => [q(c.id), q(c.name_ar), q(c.name_en), String(i)]))};

insert into public.medicines (id, name_ar, name_en, generic_name, strength, strength_en, dosage_form, pack_size, pack_size_en, manufacturer, barcode, aliases, category_id, prescription, status, is_demo) values
${values(
  medicines.map((m) => [
    q(m.id), q(m.name_ar), q(m.name_en), q(m.generic_name), q(m.strength), q(m.strength_en), q(m.dosage_form), q(m.pack_size), q(m.pack_size_en),
    'null', 'null', arr(m.aliases), q(m.category_id), q(m.prescription ?? 'unspecified'), "'approved'", 'false',
  ]),
)};

select set_config('madad.audit', '', true);

commit;
`;

writeFileSync(new URL('../supabase/seed-live.sql', import.meta.url), sql);
console.log(`supabase/seed-live.sql: ${categories.length} categories, ${medicines.length} medicines`);
